const O = 'stroke="#1b1520" stroke-width="2.4" stroke-linejoin="round" stroke-linecap="round"';

function wrap(inner) {
  return '<svg viewBox="0 0 64 64" xmlns="http://www.w3.org/2000/svg" aria-hidden="true">' + inner + "</svg>";
}
function p(fill, d) {
  return '<path ' + O + ' fill="' + fill + '" d="' + d + '"/>';
}
function c(fill, x, y, r) {
  return '<circle ' + O + ' fill="' + fill + '" cx="' + x + '" cy="' + y + '" r="' + r + '"/>';
}
function r(fill, x, y, w, h, rx) {
  return '<rect ' + O + ' fill="' + fill + '" x="' + x + '" y="' + y + '" width="' + w +
    '" height="' + h + '" rx="' + (rx || 0) + '"/>';
}
function y(fill, pts) {
  return '<polygon ' + O + ' fill="' + fill + '" points="' + pts + '"/>';
}
function l(x1, y1, x2, y2, w) {
  return '<line fill="none" stroke="#1b1520" stroke-width="' + (w || 2.4) +
    '" stroke-linecap="round" x1="' + x1 + '" y1="' + y1 + '" x2="' + x2 + '" y2="' + y2 + '"/>';
}

function gem(color) {
  return y(color || "#7f8eae", "32,10 52,24 46,52 18,52 12,24");
}

